"""Generate a prototype-only optics include; do not alter the legacy include."""
from pathlib import Path
root=Path(__file__).resolve().parents[2]/'Plugins/UnderwaterOptics/Shaders'
source=(root/'WaterOptics.ush').read_text()
source=source.replace('UNDERWATER_OPTICS_INCLUDED','SPECTRAL_WATER_OPTICS_INCLUDED')
source=source.replace('#include "/Plugin/UnderwaterOptics/OceanWaves.ush"','#include "/Plugin/UnderwaterOptics/OceanWaves.ush"\n#include "/Plugin/UnderwaterOptics/SpectralField.ush"')
source=source.replace('struct FWaterOptics\n{','struct FWaterOptics\n{\n    FSpectralField Spectral;\n    float FullWaterPath;')
