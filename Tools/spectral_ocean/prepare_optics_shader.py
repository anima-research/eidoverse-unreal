source=source.replace('Surface+80.0','Surface+400.0').replace('Surface-80.0','Surface-400.0')
source=source.replace('if(OceanEnabled<0.5)\n        {','if(FullWaterPath>0.5) medium[mediumCount++]=float2(0,lengthM);\n        else if(OceanEnabled<0.5)\n        {')
(root/'SpectralWaterOptics.ush').write_text('// Generated by Tools/spectral_ocean/prepare_optics_shader.py\n'+source)
